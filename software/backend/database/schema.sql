CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    usuario TEXT NOT NULL UNIQUE,
    pin_hash TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    activo INTEGER NOT NULL DEFAULT 1 CHECK (activo IN (0, 1)),
    fecha_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS maquinas (
    id INTEGER PRIMARY KEY,
    tipo TEXT NOT NULL UNIQUE CHECK (tipo IN ('LAVADORA', 'SECADORA')),
    estado TEXT NOT NULL DEFAULT 'LIBRE' CHECK (estado IN (
        'LIBRE', 'EN_USO', 'PENDIENTE_RETIRO', 'ENTRE_TANDAS'
    ))
);

CREATE TABLE IF NOT EXISTS solicitudes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    maquina_id INTEGER NOT NULL REFERENCES maquinas(id),
    tandas_totales INTEGER NOT NULL CHECK (tandas_totales BETWEEN 1 AND 3),
    tandas_iniciadas INTEGER NOT NULL DEFAULT 0 CHECK (tandas_iniciadas >= 0),
    disponible INTEGER NOT NULL DEFAULT 1 CHECK (disponible IN (0, 1)),
    estado TEXT NOT NULL DEFAULT 'EN_ESPERA' CHECK (estado IN (
        'EN_ESPERA', 'AUTORIZADA', 'EN_USO', 'FINALIZADA', 'CANCELADA'
    )),
    fecha_solicitud TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_finalizacion TIMESTAMP,
    CHECK (tandas_iniciadas <= tandas_totales)
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_solicitud_usuario_activa
ON solicitudes(usuario_id, maquina_id)
WHERE estado IN ('EN_ESPERA', 'AUTORIZADA', 'EN_USO');

CREATE UNIQUE INDEX IF NOT EXISTS idx_maquina_ocupada
ON solicitudes(maquina_id)
WHERE estado = 'EN_USO';

CREATE INDEX IF NOT EXISTS idx_cola
ON solicitudes(maquina_id, estado, id);

CREATE TABLE IF NOT EXISTS ciclos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitud_id BIGINT NOT NULL REFERENCES solicitudes(id),
    numero_tanda INTEGER NOT NULL CHECK (numero_tanda BETWEEN 1 AND 3),
    duracion_minutos INTEGER NOT NULL CHECK (duracion_minutos BETWEEN 1 AND 180),
    estado TEXT NOT NULL DEFAULT 'EN_CURSO' CHECK (estado IN (
        'EN_CURSO', 'PENDIENTE_RETIRO', 'RETIRADO'
    )),
    fecha_inicio TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_fin TIMESTAMP,
    fecha_retiro TIMESTAMP,
    UNIQUE (solicitud_id, numero_tanda)
);

CREATE TABLE IF NOT EXISTS notificaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    solicitud_id BIGINT REFERENCES solicitudes(id),
    mensaje TEXT NOT NULL,
    leida INTEGER NOT NULL DEFAULT 0 CHECK (leida IN (0, 1)),
    fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

